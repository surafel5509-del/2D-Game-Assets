/** Glyph box metrics shared by the atlas builder and the renderer. */
object PixelFont5x7 {
    const val GLYPH_WIDTH = 5
    const val GLYPH_HEIGHT = 7
    /** One pixel of padding around each glyph keeps nearest-neighbour sampling clean. */
    const val CELL_WIDTH = 6
    const val CELL_HEIGHT = 8
    const val COLUMNS = 16
    const val ADVANCE = 6f
    const val SIZE = 8f
    const val LINE_HEIGHT = 9f
    const val BASE_LINE = 7f

    val characters: List<Char> = PIXEL_FONT_5X7.keys.toList()

    fun rows(glyph: Char): List<String> = (PIXEL_FONT_5X7[glyph] ?: PIXEL_FONT_5X7.getValue('?')).split('/')

    fun isInk(glyph: Char, x: Int, y: Int): Boolean {
        val rows = rows(glyph)
        if (y !in rows.indices) return false
        val row = rows[y]
        return x in row.indices && row[x] == '#'
    }

    /** Rasterises the whole charset into one atlas buffer (16 columns wide). */
    fun buildAtlas(): PixelBuffer {
        val rows = (characters.size + COLUMNS - 1) / COLUMNS
        val atlas = PixelBuffer(COLUMNS * CELL_WIDTH, rows * CELL_HEIGHT)
        val ink = 0xFFFFFFFF.toInt()
        characters.forEachIndexed { index, glyph ->
            val cx = (index % COLUMNS) * CELL_WIDTH
            val cy = (index / COLUMNS) * CELL_HEIGHT
            for (y in 0 until GLYPH_HEIGHT) {
                for (x in 0 until GLYPH_WIDTH) {
                    if (isInk(glyph, x, y)) atlas[cx + x, cy + y] = ink
                }
            }
        }
        return atlas
    }
}
