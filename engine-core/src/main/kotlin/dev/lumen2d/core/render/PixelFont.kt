 * The engine ships a readable monospace bitmap font so that text works in every context without
 * an imported asset: the editor's own UI, headless CI previews, error overlays and the sample
 * games. Glyphs are authored as ASCII art (7 rows of 5 columns, `/` between rows, `#` = ink)
 * and rasterised into a texture atlas at boot by [FontManager.ensureFallback].
 *
 * Fonts imported as assets (`*.font.json` + PNG atlas, BMFont-compatible) take precedence.
 */
